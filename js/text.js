import { S } from './state.js';

// Согласование текста с полом героя.
// Все тексты игры написаны в мужском роде; здесь они превращаются в женский,
// когда игрок выбрал «Девочка». Меняются только глаголы, где подлежащее — игрок:
// после «Ты …» и в начале фразы («Работал в лаборатории.»).

// Глаголы прошедшего времени, которые в текстах относятся к герою.
const VERBS = new Set((
  'выбрал стал получил взял промолчал работал читал выступил начал решил ' +
  'опубликовал ответил выиграл вышел отдыхал отложил оплатил попал отказал ' +
  'написал проиграл предложил переболел встретил открыл пожалел запомнил ' +
  'сменил заметил успел поступил собирал гулял развозил писал ходил ' +
  'подрабатывал играл подтянул налаживал потерял медитировал поговорил ' +
  'победил поражал ладил настоял вернул собрал отдал спорил хлопнул уехал ' +
  'поменял переделал аплодировал сохранил заболел проводил продолжил назвал ' +
  'бросил заработал хотел воспринял поспорил предотвратил отстоял забыл ' +
  'сработал подписал обидел занял подождал обвинил проглотил прогулял ' +
  'проработал переосмыслил вспомнил спешил купил видел сделал взлетел спал ' +
  'сдал списал поблагодарил пригласил починил включил оставил посмотрел ' +
  'выгорел возглавил превратил воспитал сформулировал угадал замолвил ' +
  'выстрелил прогорел потребовал выдержал подорвал'
).split(/\s+/));

// Неправильные формы: у них женский род образуется не добавлением «а».
const IRREGULAR = {
  'шёл': 'шла', 'ушёл': 'ушла', 'пришёл': 'пришла', 'пошёл': 'пошла',
  'нашёл': 'нашла', 'вышел': 'вышла', 'провёл': 'провела', 'плёл': 'плела',
  'завёл': 'завела', 'смог': 'смогла', 'мог': 'могла', 'умер': 'умерла',
  'рос': 'росла', 'вырос': 'выросла', 'был': 'была', 'разнёс': 'разнесла',
  'нёс': 'несла', 'вёл': 'вела', 'сел': 'села', 'лёг': 'легла',
  'достиг': 'достигла', 'добился': 'добилась'
};

// Возвратные глаголы: «родился» → «родилась».
const REFLEXIVE = {
  'родился': 'родилась', 'оказался': 'оказалась', 'научился': 'научилась',
  'ошибся': 'ошиблась', 'появился': 'появилась', 'старался': 'старалась',
  'женился': 'женилась', 'развёлся': 'развелась', 'справился': 'справилась',
  'согласился': 'согласилась', 'удивился': 'удивилась'
};

// Существительные на «-л», которые нельзя превращать в глаголы
const NOUNS = new Set((
  'провал скандал капитал титул угол пазл сериал идеал финал канал сигнал ' +
  'материал журнал металл кристалл интервал потенциал вокал филиал'
).split(/\s+/));

function keepCase(sample, value) {
  if (sample && sample[0] === sample[0].toUpperCase()) {
    return value[0].toUpperCase() + value.slice(1);
  }
  return value;
}

function femWord(word, allowAnyVerb) {
  const low = word.toLowerCase();
  const irr = IRREGULAR[low] || REFLEXIVE[low];
  if (irr) return keepCase(word, irr);
  // Возвратные глаголы: «учился» → «училась», «занимался» → «занималась»
  if (low.endsWith('лся')) return keepCase(word, low.slice(0, -3) + 'лась');
  if (VERBS.has(low)) return keepCase(word, low + 'а');
  // В начале фразы подлежащее — герой, поэтому глагол узнаём по окончанию
  if (allowAnyVerb && low.endsWith('л') && !NOUNS.has(low)) return keepCase(word, low + 'а');
  return word;
}

/** Превращает мужской род в женский, если герой — девочка. */
export function g(text) {
  if (typeof text !== 'string' || !text) return text;
  if (!S || S.gender !== 'f') return text;

  let out = text;
  // «Ты поступил», «ты нашёл»
  out = out.replace(/(^|[^а-яёА-ЯЁ])([Тт]ы\s+)([а-яё]+)/g, (m, pre, ты, verb) => pre + ты + femWord(verb, false));
  // Начало фразы: «Работал в лаборатории.»
  out = out.replace(/(^|[.!?…]\s+)([А-ЯЁ][а-яё]+)/g, (m, pre, verb) => pre + femWord(verb, true));
  return out;
}
