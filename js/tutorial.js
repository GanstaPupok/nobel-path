/** Открывает обучение с первого шага. */
export function openTutorial(step = 0) {
  if (!S) return;
  S.pendingModal = { isTutorial: true, step };
}

/** Показывает обучение, если игрок его ещё не видел. */
export function maybeShowTutorial() {
  if (!Legacy.tutorialSeen) openTutorial(0);
}

export function markTutorialSeen() {
  if (Legacy.tutorialSeen) return;
  Legacy.tutorialSeen = true;
  saveLegacy();
}
